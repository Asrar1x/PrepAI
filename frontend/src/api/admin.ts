import { apiClient } from './client';
import {
  BatchMetrics,
  ScoreDistributionBin,
  WeakTopicMatrixRow,
  AdminCompanyReadinessRow,
  AdminStudentSummary,
  DriveActivationPayload,
  InterviewEventPayload,
  QuestionUploadStats
} from '../types/admin';

export type ReportExportType = 'full-batch' | 'weak-topics' | 'company-readiness' | 'ats-audit';

export const adminApi = {
  async getBatchAnalytics(): Promise<{
    metrics: BatchMetrics;
    scoreDistribution: ScoreDistributionBin[];
    weakTopics: WeakTopicMatrixRow[];
    companyReadiness: AdminCompanyReadinessRow[];
  }> {
    const res = await apiClient.get('/admin/batches/analytics');
    return res.data;
  },

  async getStudents(search = ''): Promise<AdminStudentSummary[]> {
    const res = await apiClient.get<AdminStudentSummary[]>('/admin/students', { params: { search } });
    return Array.isArray(res.data) ? res.data : [];
  },

  async activateCompanyDrive(payload: DriveActivationPayload): Promise<{ success: boolean; message: string }> {
    const res = await apiClient.post<{ message: string }>('/admin/batches/drive-mode', payload);
    return { success: true, message: res.data.message };
  },

  async uploadQuestions(file: File): Promise<QuestionUploadStats> {
    const formData = new FormData();
    formData.append('file', file);
    const res = await apiClient.post<QuestionUploadStats>('/admin/questions/upload', formData, {
      headers: { 'Content-Type': 'multipart/form-data' }
    });
    return res.data;
  },

  async getEvents(): Promise<InterviewEventPayload[]> {
    const res = await apiClient.get<InterviewEventPayload[]>('/admin/events');
    return Array.isArray(res.data) ? res.data : [];
  },

  async createEvent(event: InterviewEventPayload): Promise<{ success: boolean }> {
    await apiClient.post('/admin/events', event);
    return { success: true };
  },

  // Downloads a CSV or PDF export generated by the server and saves it in the browser.
  async exportReport(type: ReportExportType, format: 'csv' | 'pdf', batch?: string): Promise<string> {
    const res = await apiClient.get<Blob>('/admin/reports/export', {
      params: { type, format, batch },
      responseType: 'blob',
      timeout: 60000
    });
    const disposition = String(res.headers['content-disposition'] || '');
    const match = disposition.match(/filename="([^"]+)"/);
    const filename = match ? match[1] : `prepai_${type}.${format}`;
    const url = URL.createObjectURL(res.data);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    a.remove();
    URL.revokeObjectURL(url);
    return filename;
  }
};
