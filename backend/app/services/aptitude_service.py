async def start_session(
    db: AsyncSession,
    user_id: uuid.UUID,
    role_slug: str,
    company_slug: Optional[str],
    mode: str = "adaptive",
    duration_minutes: int = 30,
) -> AptitudeSession:
    s = AptitudeSession(
        id=uuid.uuid4(),
        user_id=user_id,
        job_role=role_slug,
        company_pattern=company_slug,
        mode=mode,
        duration_minutes=duration_minutes,
        total_questions=0,
        correct_count=0,
        wrong_count=0,
        skipped_count=0,
        score=0.0,
        questions_data=[],
        category_scores={},
        weak_topics=[],
    )
    db.add(s)
    await db.commit()
    await db.refresh(s)
    return s


async def get_session(
    db: AsyncSession, session_id: uuid.UUID, user_id: uuid.UUID
) -> Optional[AptitudeSession]:
    r = await db.execute(
        select(AptitudeSession).where(
            AptitudeSession.id == session_id, AptitudeSession.user_id == user_id
        )
    )
    return r.scalars().first()


async def record_answer(
    db: AsyncSession,
    session: AptitudeSession,
    question: Dict[str, Any],
    selected_index: int,
    is_correct: bool,
    time_taken: int,
) -> None:
    history = list(session.questions_data or [])
    history.append(
        {
            "question_id": question.get("id"),
            "category": question.get("category"),
            "difficulty": question.get("difficulty"),
            "selected_index": selected_index,
            "correct_index": question.get("correct_index"),
            "is_correct": is_correct,
            "time_taken": time_taken,
            "topic": question.get("topic"),
        }
    )
    session.questions_data = history
    session.total_questions = (session.total_questions or 0) + 1
    if is_correct:
        session.correct_count = (session.correct_count or 0) + 1
    else:
        session.wrong_count = (session.wrong_count or 0) + 1

    # Recompute category_scores (weighted by difficulty)
    weights = {"easy": 1.0, "medium": 1.5, "hard": 2.0}
    cat_scores: Dict[str, Dict[str, float]] = {}
    for h in history:
        c = h.get("category") or "unknown"
        d = h.get("difficulty") or "easy"
        bucket = cat_scores.setdefault(c, {"correct": 0, "weight": 0.0, "earned": 0.0})
        bucket["weight"] += weights.get(d, 1.0)
        if h.get("is_correct"):
            bucket["correct"] += 1
            bucket["earned"] += weights.get(d, 1.0)
    session.category_scores = {
        c: {
            "correct": v["correct"],
            "total": sum(1 for h in history if h.get("category") == c),
            "weighted_pct": round(100 * v["earned"] / v["weight"]) if v["weight"] else 0,
        }
        for c, v in cat_scores.items()
    }
    # Weak topics = those with weighted_pct < 60
    session.weak_topics = [
        {"category": c, "weighted_pct": s["weighted_pct"]}
        for c, s in session.category_scores.items()
        if s["weighted_pct"] < 60
    ]
    # Composite score
    total_weight = sum(v["weight"] for v in cat_scores.values())
    earned = sum(v["earned"] for v in cat_scores.values())
    session.score = round(100 * earned / total_weight) if total_weight else 0.0
    # Max difficulty reached
    reached = [
        DIFFICULTIES.index(h["difficulty"])
        for h in history
        if h.get("difficulty") in DIFFICULTIES
    ]
    if reached:
        session.max_difficulty_reached = DIFFICULTIES[max(reached)]
    await db.commit()
    await db.refresh(session)


async def get_solution(question_id: str) -> Optional[Dict[str, Any]]:
    cached = await redis_client.get(f"solution:{question_id}")
    if cached:
        try:
            return json.loads(cached)
        except Exception:
            return None
    return None
