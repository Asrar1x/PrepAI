async def generate_question(
    category: str,
    difficulty: str,
    role: Optional[str] = None,
    company: Optional[str] = None,
    use_cache: bool = True,
) -> Dict[str, Any]:
    """Generate one question. Order of preference:
    Redis cache (per-rotated slot) → Claude Haiku 4.5 → local GPT-2 model → fallback bank.
    """
    # Rotate across 4 cache slots per (category, difficulty, role, company) to
    # avoid returning the same question twice in a row.
    import time as _t
    slot = int(_t.time() // 600) % 4  # 10-min buckets, 4 slots
    cache_key = f"q:{category}:{difficulty}:{role or 'x'}:{company or 'x'}:slot{slot}"
    if use_cache:
        cached = await redis_client.get(cache_key)
        if cached:
            try:
                return json.loads(cached)
            except Exception:
                pass

    q: Dict[str, Any]
    if settings.CLAUDE_API_KEY:
        try:
            q = await _generate_with_claude(category, difficulty, role, company)
            q["source"] = q.get("source", "claude")
        except Exception as e:
            logger.warning("Claude aptitude gen failed, trying local: %s", e)
            q = _generate_with_local_model(category, difficulty, role)
    else:
        q = _generate_with_local_model(category, difficulty, role)

    q.setdefault("category", category)
    q.setdefault("difficulty", difficulty)
    q["id"] = q.get("id") or str(uuid.uuid4())

    # Cache the solution (explanation + correct answer) for 7d
    solution_payload = {
        "correct_index": q.get("correct_index"),
        "explanation": q.get("explanation"),
        "category": q.get("category"),
        "difficulty": q.get("difficulty"),
        "topic": q.get("topic"),
    }
    try:
        await redis_client.set(
            f"solution:{q['id']}",
            json.dumps(solution_payload),
            ex=settings.SOLUTION_CACHE_TTL,
        )
        await redis_client.set(
            cache_key,
            json.dumps(q),
            ex=settings.QUESTION_CACHE_TTL,
        )
    except Exception as e:
        logger.debug("Redis cache write failed (non-fatal): %s", e)

    return q


