def adjust_difficulty(
    history: List[Dict[str, Any]],
    category: str,
) -> str:
    """One streak tracker per category. +3 in a row → bump up, +2 wrong → bump down."""
    cat_history = [h for h in history if h.get("category") == category]
    streak_correct = 0
    streak_wrong = 0
    for h in reversed(cat_history):
        if h.get("is_correct"):
            streak_correct += 1
            streak_wrong = 0
        else:
            streak_wrong += 1
            streak_correct = 0
        if streak_correct >= 3 or streak_wrong >= 2:
            break

    last_diff = cat_history[-1].get("difficulty", "easy") if cat_history else "easy"
    idx = DIFFICULTIES.index(last_diff) if last_diff in DIFFICULTIES else 0
    if streak_correct >= 3 and idx < len(DIFFICULTIES) - 1:
        idx += 1
    elif streak_wrong >= 2 and idx > 0:
        idx -= 1
    return DIFFICULTIES[idx]


