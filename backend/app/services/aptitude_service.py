"""Aptitude test engine — Module 2.

Adaptive per-category difficulty (one streak tracker per category).
Question-generation order (matches PrepAI doc §2.3 + §10):

  1. Redis solution cache (4 rotating 10-min slots)
  2. **Model 2** (local GPT-2 question generator) — no API cost
  3. Claude Haiku 4.5 — quality boost on top of the local model
  4. Deterministic placeholder bank

The local model is preferred because (a) the user explicitly asked for
"no external API dependency where possible", (b) Model 2 is fine-tuned
on the exact prompt template used here, and (c) the hot path stays
sub-200ms with no LLM round-trip.
"""
