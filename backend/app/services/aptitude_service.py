GENERATION_SYSTEM = """You are an expert aptitude test author for Indian engineering placement exams.
Generate one fresh, original multiple-choice question.
Output STRICT JSON only — no prose, no markdown fences."""

GENERATION_USER_TEMPLATE = """Category: {category}
Difficulty: {difficulty}
Target role (optional): {role}
Target company (optional): {company}

Output JSON with keys:
  id: string (uuid-shaped, e.g. "{stub}")
  question: string
  options: list of 4 short strings
  correct_index: integer 0..3
  explanation: 2-3 sentence step-by-step solution
  topic: 1-3 word sub-topic
  estimated_seconds: integer 45-180
"""


async def _generate_with_claude(
    category: str,
    difficulty: str,
    role: Optional[str],
    company: Optional[str],
) -> Dict[str, Any]:
    """Call Claude Haiku 4.5 to generate one fresh question."""
    import anthropic

    client = anthropic.AsyncAnthropic(api_key=settings.CLAUDE_API_KEY)
    prompt = GENERATION_USER_TEMPLATE.format(
        category=category,
        difficulty=difficulty,
        role=role or "any",
        company=company or "any",
        stub=str(uuid.uuid4()),
    )
    response = await client.messages.create(
        model=settings.CLAUDE_MODEL_FAST,
        max_tokens=1024,
        system=GENERATION_SYSTEM,
        messages=[{"role": "user", "content": prompt}],
    )
    text = response.content[0].text.strip()
    if text.startswith("```"):
        text = text.strip("`")
        if text.startswith("json"):
            text = text[4:]
        if text.endswith("```"):
            text = text[:-3]
        text = text.strip()
    return json.loads(text)


def _generate_with_local_model(
    category: str, difficulty: str, role: Optional[str]
) -> Dict[str, Any]:
    """Use the locally trained GPT-2 question generator as a fallback."""
    try:
        # The local model signature is (role, topic, prev_q, answer, quality)
        text = ml_models.generate_question(
            role or "any", category, "", "", difficulty
        ) or ""
        return {
            "id": str(uuid.uuid4()),
            "question": (text or f"[{difficulty}] {category} sample question").strip(),
            "options": ["Option A", "Option B", "Option C", "Option D"],
            "correct_index": 0,
            "explanation": "Generated by the local fallback model; treat the first option as correct placeholder.",
            "topic": category,
            "estimated_seconds": 90,
            "source": "local_fallback",
        }
    except Exception as e:  # pragma: no cover - local model may not be loaded
        logger.warning("Local model question generation failed: %s", e)
        return _fallback_question(category, difficulty)


